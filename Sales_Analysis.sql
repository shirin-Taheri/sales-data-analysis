# Question 13 — Which customers fall within the top 10 ranks based on the number of orders placed, including ties?
with customer_orders aS (
    select
        c.customer_id,
        c.customer_name,
        COUNT(o.order_id) as number_of_orders
    from customers as c
    join orders as o
	on c.customer_id = o.customer_id
    group by
	c.customer_id,
	c.customer_name
),
ranked_customers as (
    select
        customer_id,
        customer_name,
        number_of_orders,
        rank() over (
            order by number_of_orders DESC
        ) as customer_rank
    from customer_orders
)
select
    customer_id,
    customer_name,
    number_of_orders,
    customer_rank
from ranked_customers
where customer_rank <= 10
order by customer_rank, 
customer_name;

