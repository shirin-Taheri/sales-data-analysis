# Question 25 — What is the average order value across all orders?
WITH order_revenue AS
(
    SELECT
        od.order_id,
        SUM(s.sales) AS total_revenue
    FROM order_details AS od
    JOIN sales AS s
        ON od.orderdetail_id = s.orderdetail_id
    GROUP BY od.order_id
)
SELECT
    ROUND(AVG(total_revenue), 2) AS average_order_value
FROM order_revenue;

