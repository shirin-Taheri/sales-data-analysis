# Question 29 — How did annual recorded sales change for each product line based on records with matching product IDs?
with total_sales_of_each_year as 
(
select p.product_line, 
year(o.order_date) as `year`, 
round(sum(s.sales),2) as total_sales
from products as p 
join order_details as od
on p.product_id = od.product_id
join orders as o
on od.order_id = o.order_id
join sales as s
on od.orderdetail_id = s.orderdetail_id
group by p.product_line, 
year(o.order_date) 
),
previous_sales as 
(
select product_line, 
`year`, 
total_sales, 
lag(total_sales) over(partition by product_line order by `year`) as previous_total_sales
from total_sales_of_each_year
)
select * , 
round(total_sales - previous_total_sales,2) as revenue_change
from previous_sales
order by product_line, 
`year`;

# Question 30 — What percentage of orders in each year were shipped?
with shipped_orders as 
(
select 
year(order_date) as `year`,
count(`status`) as number_of_shipped_orders
from orders
where `status` = 'shipped'
group by `year`
),
total_yearly_orders as 
(select 
year(order_date) as `year`,
count(`status`) as total_orders_each_year
from orders 
group by `year`
)
select so.`year`,
so.number_of_shipped_orders, 
tyo.total_orders_each_year , 
round((so.number_of_shipped_orders /tyo.total_orders_each_year)*100,2) as percentage_of_shipped_orders_yearly
from shipped_orders as so
join total_yearly_orders as tyo
on so.year = tyo.year
order by so.`year`;
