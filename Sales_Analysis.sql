/*
DATA QUALITY NOTE 1: SALES VALUES

The source dataset contains inconsistencies between the recorded SALES
values and the values calculated as QUANTITYORDERED * PRICEEACH.

For this analysis, the SALES column is used as the recorded sales measure.
The discrepancy is acknowledged as a data quality limitation, and the
cause has not been independently established.
*/

/*
DATA QUALITY NOTE 2: PRODUCT RELATIONSHIPS

Product IDs in order_details do not consistently match
the product IDs in the products table.

Product-related queries using INNER JOIN include only
matching records and do not represent the full dataset.

This limitation applies to Questions 7, 8, 15, 16, 24, and 29.
Their results should be interpreted with caution.
*/

